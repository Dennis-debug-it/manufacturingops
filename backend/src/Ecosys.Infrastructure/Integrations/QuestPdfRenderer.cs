using Ecosys.Shared.Contracts.Integration;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace Ecosys.Infrastructure.Integrations;

internal sealed class QuestPdfRenderer : IPdfRenderer
{
    public byte[] RenderWorkOrderReportPdf(string title, IReadOnlyCollection<string> sections)
    {
        QuestPDF.Settings.License = LicenseType.Community;

        return Document.Create(container =>
            container.Page(page =>
            {
                page.Margin(32);
                page.Header().Text(title).FontSize(20).SemiBold();
                page.Content().Column(column =>
                {
                    foreach (var section in sections)
                    {
                        column.Item().PaddingVertical(4).Text(section);
                    }
                });
                page.Footer().AlignCenter().Text(text =>
                {
                    text.Span("Generated by Ecosys");
                });
            }))
            .GeneratePdf();
    }

    public byte[] RenderWorkOrderReportPdf(WorkOrderReportPdfModel report)
    {
        QuestPDF.Settings.License = LicenseType.Community;

        // ── Resolve template settings ────────────────────────────────────────
        var cfg          = report.TemplateConfig ?? new ReportTemplateConfig();
        var primaryColor = cfg.ReportPrimaryColor   ?? report.PrimaryColor;
        var borderColor  = cfg.ReportSecondaryColor ?? report.SecondaryColor;
        var font         = cfg.FontFamily is "Helvetica" or "Arial" or "Times New Roman"
                             ? cfg.FontFamily : "Helvetica";

        var enabledSections = cfg.Sections
            .OrderBy(s => s.Order)
            .Where(s => s.Enabled)
            .Select(s => s.Id)
            .ToHashSet(StringComparer.OrdinalIgnoreCase);
        bool On(string id) => enabledSections.Count == 0 || enabledSections.Contains(id);

        return Document.Create(container =>
            container.Page(page =>
            {
                page.Margin(28);
                page.DefaultTextStyle(x => x.FontSize(10).FontFamily(font));

                page.Header().Column(header =>
                {
                    // ── Company identity row ─────────────────────────────────
                    header.Item().Row(row =>
                    {
                        var hasLogo = report.LogoBytes is { Length: > 0 };

                        if (hasLogo && cfg.LogoAlignment == LogoAlignment.Left)
                            row.ConstantItem(80).PaddingRight(12).Image(report.LogoBytes!).FitArea();

                        row.RelativeItem().Column(col =>
                        {
                            if (cfg.ShowCompanyName)
                                col.Item().Text(report.CompanyName).FontSize(18).SemiBold().FontColor(primaryColor);

                            if (cfg.ShowCompanyContact)
                            {
                                var contactParts = new[] { report.CompanyPhone, report.CompanyEmail, report.CompanyAddress }
                                    .Where(x => !string.IsNullOrWhiteSpace(x));
                                var contactLine = string.Join("  ·  ", contactParts);
                                if (!string.IsNullOrWhiteSpace(contactLine))
                                    col.Item().Text(contactLine).FontSize(8).FontColor(Colors.Grey.Darken1);
                            }
                        });

                        if (hasLogo && cfg.LogoAlignment == LogoAlignment.Right)
                            row.ConstantItem(80).PaddingLeft(12).Image(report.LogoBytes!).FitArea();

                        if (hasLogo && cfg.LogoAlignment == LogoAlignment.Center)
                        {
                            // Already placed text; add centered logo after it (secondary position)
                        }
                    });

                    // ── Work order identity row ──────────────────────────────
                    header.Item().PaddingTop(6).BorderBottom(1).BorderColor(borderColor).PaddingBottom(6)
                        .Row(row =>
                        {
                            row.RelativeItem().Text($"{report.WorkOrderNumber}  |  {report.Title}").FontSize(13).SemiBold();
                            row.AutoItem().Text(text =>
                            {
                                text.Span("Generated: ").SemiBold().FontSize(9);
                                text.Span(report.GeneratedAtLabel).FontSize(9).FontColor(Colors.Grey.Darken1);
                            });
                        });
                });

                page.Content().Column(column =>
                {
                    column.Spacing(12);

                    if (On("service-details"))
                        column.Item().Element(x => RenderSection(x, borderColor, "Service details", new[]
                        {
                            ("Client", report.ClientName),
                            ("Site / Location", report.SiteLabel),
                            ("Asset", report.AssetName),
                            ("Asset details", report.AssetDetails),
                            ("Technician / Team", report.TechnicianTeam),
                            ("Template", report.TemplateVersion.HasValue
                                ? $"{report.TemplateName} v{report.TemplateVersion}"
                                : report.TemplateName)
                        }));

                    if (On("problem"))
                        column.Item().Element(x => RenderParagraphSection(x, borderColor, "Problem reported", report.ReportedProblem));

                    if (On("findings"))
                        column.Item().Element(x => RenderParagraphSection(x, borderColor, "Findings", report.Findings));

                    if (On("work-done"))
                        column.Item().Element(x => RenderParagraphSection(x, borderColor, "Work done", report.WorkDone));

                    if (On("timestamps"))
                        column.Item().Element(x => RenderSection(x, borderColor, "Timestamps",
                            report.Timestamps.Select(t => (t.Label, t.Value)).ToArray()));

                    if (On("checklist") && report.ChecklistSections.Count > 0)
                        column.Item().Element(x => RenderChecklistSection(x, borderColor, report.ChecklistSections));

                    if (On("materials"))
                        column.Item().Element(x => RenderMaterialsSection(x, borderColor, report.Materials));

                    if (On("photos"))
                    {
                        foreach (var group in report.PhotoGroups.Where(x => x.Photos.Count > 0))
                            column.Item().Element(x => RenderPhotoGroup(x, borderColor, group));
                    }

                    if (On("signatures") && report.Signatures.Count > 0)
                        column.Item().Element(x => RenderSignatureSection(x, borderColor, report.Signatures));
                });

                page.Footer().BorderTop(1).BorderColor(borderColor).PaddingTop(6).Row(row =>
                {
                    row.RelativeItem().Column(col =>
                    {
                        col.Item().Text(report.CompanyName).FontSize(8).SemiBold().FontColor(Colors.Grey.Darken2);
                        var footerContact = new[] { report.CompanyPhone, report.CompanyEmail }
                            .Where(x => !string.IsNullOrWhiteSpace(x));
                        var footerLine = string.Join("  ·  ", footerContact);
                        if (!string.IsNullOrWhiteSpace(footerLine))
                            col.Item().Text(footerLine).FontSize(7).FontColor(Colors.Grey.Darken1);
                        // Custom footer message from template config
                        if (!string.IsNullOrWhiteSpace(cfg.FooterText))
                            col.Item().Text(cfg.FooterText).FontSize(7).Italic().FontColor(Colors.Grey.Darken1);
                        if (report.ShowPoweredByEcosys)
                            col.Item().Text("Powered by Ecosys").FontSize(7).FontColor(Colors.Grey.Lighten1);
                    });

                    row.AutoItem().AlignBottom().Text(text =>
                    {
                        text.Span("Page ").FontSize(8).FontColor(Colors.Grey.Darken1);
                        text.CurrentPageNumber().FontSize(8).FontColor(Colors.Grey.Darken1);
                        text.Span(" of ").FontSize(8).FontColor(Colors.Grey.Darken1);
                        text.TotalPages().FontSize(8).FontColor(Colors.Grey.Darken1);
                    });
                });
            }))
            .GeneratePdf();
    }

    private static void RenderSection(IContainer container, string borderColor, string title, IReadOnlyCollection<(string Label, string? Value)> lines)
    {
        container.Border(1).BorderColor(borderColor).Padding(10).Column(column =>
        {
            column.Spacing(6);
            column.Item().Text(title).FontSize(12).SemiBold();
            foreach (var (label, value) in lines.Where(x => !string.IsNullOrWhiteSpace(x.Value)))
            {
                column.Item().Text(text =>
                {
                    text.Span($"{label}: ").SemiBold();
                    text.Span(value);
                });
            }
        });
    }

    private static void RenderParagraphSection(IContainer container, string borderColor, string title, string? body)
    {
        container.Border(1).BorderColor(borderColor).Padding(10).Column(column =>
        {
            column.Spacing(6);
            column.Item().Text(title).FontSize(12).SemiBold();
            column.Item().Text(string.IsNullOrWhiteSpace(body) ? "Not recorded." : body);
        });
    }

    private static void RenderMaterialsSection(IContainer container, string borderColor, IReadOnlyCollection<WorkOrderReportPdfMaterial> materials)
    {
        container.Border(1).BorderColor(borderColor).Padding(10).Column(column =>
        {
            column.Spacing(6);
            column.Item().Text("Materials / spares used").FontSize(12).SemiBold();
            if (materials.Count == 0)
            {
                column.Item().Text("No materials recorded.");
                return;
            }

            foreach (var material in materials)
            {
                column.Item().Text(text =>
                {
                    text.Span(material.Name).SemiBold();
                    text.Span($" - {material.QuantityUsed} {material.UnitOfMeasure}");
                    if (material.UnitCost.HasValue)
                    {
                        text.Span($" @ {material.UnitCost.Value:0.00}");
                    }

                    text.Span(material.Chargeable ? " - Chargeable" : " - Non-chargeable");
                });

                if (!string.IsNullOrWhiteSpace(material.Notes))
                {
                    column.Item().PaddingLeft(8).Text(material.Notes).FontSize(9).FontColor(Colors.Grey.Darken1);
                }
            }
        });
    }

    private static void RenderChecklistSection(IContainer container, string borderColor, IReadOnlyCollection<WorkOrderReportPdfChecklistSection> sections)
    {
        container.Border(1).BorderColor(borderColor).Padding(10).Column(column =>
        {
            column.Spacing(8);
            column.Item().Text("Checklist responses").FontSize(12).SemiBold();

            foreach (var section in sections)
            {
                column.Item().Text(section.SectionName).FontSize(10).SemiBold().FontColor(Colors.Grey.Darken2);
                foreach (var item in section.Items)
                {
                    column.Item().PaddingLeft(8).Column(itemColumn =>
                    {
                        itemColumn.Spacing(2);
                        itemColumn.Item().Text(text =>
                        {
                            text.Span(item.Question).SemiBold();
                            if (item.IsRequired)
                            {
                                text.Span(" (required)").FontSize(8).FontColor(Colors.Grey.Darken1);
                            }
                        });
                        var value = string.IsNullOrWhiteSpace(item.ResponseValue) ? "Not answered" : item.ResponseValue;
                        itemColumn.Item().Text($"{item.InputType}: {value}{(string.IsNullOrWhiteSpace(item.Unit) ? string.Empty : $" {item.Unit}")}").FontSize(9);
                        if (!string.IsNullOrWhiteSpace(item.Remarks))
                        {
                            itemColumn.Item().Text($"Remarks: {item.Remarks}").FontSize(9).FontColor(Colors.Grey.Darken1);
                        }

                        if (item.EvidenceRequired)
                        {
                            itemColumn.Item().Text(
                                string.IsNullOrWhiteSpace(item.EvidenceUrl)
                                    ? "Evidence required: missing"
                                    : $"Evidence: {item.EvidenceUrl}")
                                .FontSize(9).FontColor(Colors.Grey.Darken1);
                        }
                    });
                }
            }
        });
    }

    private static void RenderPhotoGroup(IContainer container, string borderColor, WorkOrderReportPdfPhotoGroup group)
    {
        container.Border(1).BorderColor(borderColor).Padding(10).Column(column =>
        {
            column.Spacing(8);
            column.Item().Text(group.Category).FontSize(12).SemiBold();
            foreach (var photo in group.Photos)
            {
                column.Item().Column(photoColumn =>
                {
                    photoColumn.Spacing(4);
                    if (photo.ImageBytes is { Length: > 0 })
                    {
                        photoColumn.Item().Height(160).Image(photo.ImageBytes).FitArea();
                    }
                    else if (!string.IsNullOrWhiteSpace(photo.PublicUrl))
                    {
                        photoColumn.Item().Text($"Image stored at: {photo.PublicUrl}").FontColor(Colors.Blue.Darken2);
                    }

                    photoColumn.Item().Text(photo.Caption).FontSize(9);
                });
            }
        });
    }

    private static void RenderSignatureSection(IContainer container, string borderColor, IReadOnlyCollection<WorkOrderReportPdfSignature> signatures)
    {
        container.Border(1).BorderColor(borderColor).Padding(10).Column(column =>
        {
            column.Spacing(8);
            column.Item().Text("Signatures").FontSize(12).SemiBold();

            foreach (var signature in signatures)
            {
                column.Item().Column(signatureColumn =>
                {
                    signatureColumn.Spacing(4);
                    signatureColumn.Item().Text($"{signature.SignatureType}: {signature.SignerName}").SemiBold();
                    if (!string.IsNullOrWhiteSpace(signature.SignerRole))
                    {
                        signatureColumn.Item().Text(signature.SignerRole).FontSize(9);
                    }

                    signatureColumn.Item().Text($"Captured at {signature.CapturedAtLabel}").FontSize(9);
                    if (signature.ImageBytes is { Length: > 0 })
                    {
                        signatureColumn.Item().Height(90).Image(signature.ImageBytes).FitArea();
                    }

                    if (!string.IsNullOrWhiteSpace(signature.Comment))
                    {
                        signatureColumn.Item().Text(signature.Comment).FontSize(9).FontColor(Colors.Grey.Darken1);
                    }
                });
            }
        });
    }

    // ── Invoice PDF ──────────────────────────────────────────────────────────

    public byte[] RenderInvoicePdf(InvoicePdfModel model)
    {
        QuestPDF.Settings.License = LicenseType.Community;

        var primary = model.PrimaryColor;
        var altRow  = Colors.Grey.Lighten4;
        var invoiceFont = model.FontFamily is "Helvetica" or "Arial" or "Times New Roman"
            ? model.FontFamily : "Helvetica";

        return Document.Create(container =>
            container.Page(page =>
            {
                page.Margin(32);
                page.DefaultTextStyle(x => x.FontSize(10).FontFamily(invoiceFont));

                if (!string.IsNullOrWhiteSpace(model.WatermarkText))
                {
                    page.Background().AlignCenter().AlignMiddle()
                        .Text(model.WatermarkText.ToUpperInvariant())
                        .FontSize(64).SemiBold().FontColor(Colors.Grey.Lighten3);
                }

                // ── Header ────────────────────────────────────────────────
                page.Header().Column(header =>
                {
                    header.Item().Row(row =>
                    {
                        // Left: company identity
                        row.RelativeItem().Column(col =>
                        {
                            col.Item().Text(model.CompanyName).FontSize(18).SemiBold().FontColor(primary);

                            var contactParts = new[] { model.CompanyPhone, model.CompanyAddress }
                                .Where(x => !string.IsNullOrWhiteSpace(x));
                            var contactLine = string.Join("  ·  ", contactParts);
                            if (!string.IsNullOrWhiteSpace(contactLine))
                                col.Item().Text(contactLine).FontSize(8).FontColor(Colors.Grey.Darken1);
                        });

                        // Right: invoice title + number
                        row.AutoItem().AlignRight().Column(col =>
                        {
                            col.Item().Text("INVOICE").FontSize(22).SemiBold().FontColor(primary);
                            col.Item().Text(model.InvoiceNumber).FontSize(11).FontColor(Colors.Grey.Darken2);
                        });
                    });

                    header.Item().PaddingTop(8).BorderBottom(2).BorderColor(primary);
                });

                // ── Content ───────────────────────────────────────────────
                page.Content().PaddingTop(12).Column(column =>
                {
                    column.Spacing(14);

                    // Bill-to + details strip
                    column.Item().Row(row =>
                    {
                        // Bill To block
                        row.RelativeItem().Border(1).BorderColor(Colors.Grey.Lighten2).Padding(10).Column(col =>
                        {
                            col.Spacing(3);
                            col.Item().Text("BILL TO").FontSize(8).SemiBold().FontColor(Colors.Grey.Darken1);
                            col.Item().Text(model.ClientName).SemiBold();
                            if (!string.IsNullOrWhiteSpace(model.ClientAddress))
                                col.Item().Text(model.ClientAddress).FontSize(9).FontColor(Colors.Grey.Darken1);
                            if (!string.IsNullOrWhiteSpace(model.ClientEmail))
                                col.Item().Text(model.ClientEmail).FontSize(9).FontColor(Colors.Grey.Darken1);
                        });

                        row.ConstantItem(16); // spacer

                        // Details strip
                        row.RelativeItem().Border(1).BorderColor(Colors.Grey.Lighten2).Padding(10).Column(col =>
                        {
                            col.Spacing(4);
                            col.Item().Row(r =>
                            {
                                r.RelativeItem().Text("Invoice Date").FontSize(8).SemiBold().FontColor(Colors.Grey.Darken1);
                                r.AutoItem().Text(model.InvoiceDate.ToString("dd MMM yyyy"));
                            });
                            col.Item().Row(r =>
                            {
                                r.RelativeItem().Text("Due Date").FontSize(8).SemiBold().FontColor(Colors.Grey.Darken1);
                                r.AutoItem().Text(model.DueDate.ToString("dd MMM yyyy"));
                            });
                            col.Item().Row(r =>
                            {
                                r.RelativeItem().Text("Status").FontSize(8).SemiBold().FontColor(Colors.Grey.Darken1);
                                r.AutoItem().Text(model.Status).SemiBold().FontColor(primary);
                            });
                            col.Item().Row(r =>
                            {
                                r.RelativeItem().Text("Currency").FontSize(8).SemiBold().FontColor(Colors.Grey.Darken1);
                                r.AutoItem().Text(model.Currency);
                            });
                        });
                    });

                    // Line items table
                    column.Item().Table(table =>
                    {
                        table.ColumnsDefinition(cols =>
                        {
                            cols.RelativeColumn(4);    // Description
                            cols.RelativeColumn(1.2f); // Qty
                            cols.RelativeColumn(1);    // Unit
                            cols.RelativeColumn(1.5f); // Rate
                            cols.RelativeColumn(1.5f); // Line Total
                            cols.RelativeColumn(1);    // Tax %
                            cols.RelativeColumn(1.5f); // Grand Total
                        });

                        // Header row
                        IContainer HeaderCell(IContainer c) =>
                            c.Background(primary).Padding(6).AlignMiddle();

                        table.Header(h =>
                        {
                            h.Cell().Element(HeaderCell).Text("Description").FontSize(9).SemiBold().FontColor(Colors.White);
                            h.Cell().Element(HeaderCell).AlignRight().Text("Qty").FontSize(9).SemiBold().FontColor(Colors.White);
                            h.Cell().Element(HeaderCell).Text("Unit").FontSize(9).SemiBold().FontColor(Colors.White);
                            h.Cell().Element(HeaderCell).AlignRight().Text("Rate").FontSize(9).SemiBold().FontColor(Colors.White);
                            h.Cell().Element(HeaderCell).AlignRight().Text("Line Total").FontSize(9).SemiBold().FontColor(Colors.White);
                            h.Cell().Element(HeaderCell).AlignRight().Text("Tax %").FontSize(9).SemiBold().FontColor(Colors.White);
                            h.Cell().Element(HeaderCell).AlignRight().Text("Grand Total").FontSize(9).SemiBold().FontColor(Colors.White);
                        });

                        // Data rows (alternating)
                        for (var i = 0; i < model.Lines.Count; i++)
                        {
                            var line = model.Lines[i];
                            var bg = i % 2 == 0 ? Colors.White : altRow;

                            IContainer DataCell(IContainer c) =>
                                c.Background(bg).BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Padding(6).AlignMiddle();

                            table.Cell().Element(DataCell).Text(line.Description).FontSize(9);
                            table.Cell().Element(DataCell).AlignRight().Text(line.Quantity.ToString("0.##")).FontSize(9);
                            table.Cell().Element(DataCell).Text(line.Unit).FontSize(9);
                            table.Cell().Element(DataCell).AlignRight().Text($"{line.UnitRate:N2}").FontSize(9);
                            table.Cell().Element(DataCell).AlignRight().Text($"{line.LineTotal:N2}").FontSize(9);
                            table.Cell().Element(DataCell).AlignRight().Text($"{line.TaxRate:0.##}%").FontSize(9);
                            table.Cell().Element(DataCell).AlignRight().Text($"{line.GrandTotal:N2}").FontSize(9).SemiBold();
                        }
                    });

                    // Totals block (right-aligned)
                    column.Item().AlignRight().Width(240).Column(totals =>
                    {
                        totals.Spacing(0);

                        void TotalRow(string label, string value, bool bold = false, bool highlight = false)
                        {
                            totals.Item()
                                .Background(highlight ? primary : Colors.White)
                                .BorderBottom(1).BorderColor(Colors.Grey.Lighten3)
                                .Padding(6).Row(r =>
                                {
                                    var lbl = r.RelativeItem().Text(label).FontSize(9);
                                    if (bold) lbl = lbl.SemiBold();
                                    lbl.FontColor(highlight ? Colors.White : Colors.Grey.Darken2);

                                    var val = r.AutoItem().Text(value).FontSize(9);
                                    if (bold) val = val.SemiBold();
                                    val.FontColor(highlight ? Colors.White : Colors.Black);
                                });
                        }

                        TotalRow("Subtotal", $"{model.Currency} {model.Subtotal:N2}");
                        TotalRow("Tax", $"{model.Currency} {model.TaxAmount:N2}");
                        TotalRow("Total", $"{model.Currency} {model.TotalAmount:N2}", bold: true);
                        TotalRow("Amount Paid", $"{model.Currency} {model.AmountPaid:N2}");
                        TotalRow("Balance Due", $"{model.Currency} {model.Balance:N2}", bold: true, highlight: true);
                    });

                    // Notes
                    if (!string.IsNullOrWhiteSpace(model.Notes))
                    {
                        column.Item().Border(1).BorderColor(Colors.Grey.Lighten2).Padding(10).Column(col =>
                        {
                            col.Spacing(4);
                            col.Item().Text("Notes").FontSize(10).SemiBold();
                            col.Item().Text(model.Notes).FontSize(9).FontColor(Colors.Grey.Darken1);
                        });
                    }

                    // Bank / payment details
                    if (!string.IsNullOrWhiteSpace(model.BankDetails) || !string.IsNullOrWhiteSpace(model.PaymentInstructions))
                    {
                        column.Item().Border(1).BorderColor(Colors.Grey.Lighten2).Padding(10).Column(col =>
                        {
                            col.Spacing(4);
                            col.Item().Text("Payment Details").FontSize(10).SemiBold().FontColor(primary);
                            if (!string.IsNullOrWhiteSpace(model.BankDetails))
                                col.Item().Text(model.BankDetails).FontSize(9).FontColor(Colors.Grey.Darken2);
                            if (!string.IsNullOrWhiteSpace(model.PaymentInstructions))
                                col.Item().Text(model.PaymentInstructions).FontSize(9).FontColor(Colors.Grey.Darken1);
                        });
                    }

                    // Terms
                    if (!string.IsNullOrWhiteSpace(model.TermsText))
                    {
                        column.Item().Column(col =>
                        {
                            col.Spacing(3);
                            col.Item().Text("Terms & Conditions").FontSize(9).SemiBold().FontColor(Colors.Grey.Darken2);
                            col.Item().Text(model.TermsText).FontSize(8).FontColor(Colors.Grey.Darken1);
                        });
                    }
                });

                // ── Footer ────────────────────────────────────────────────
                page.Footer().BorderTop(1).BorderColor(Colors.Grey.Lighten2).PaddingTop(6).Column(footer =>
                {
                    footer.Item().Row(row =>
                    {
                        row.RelativeItem().Text(model.CompanyName).FontSize(8).FontColor(Colors.Grey.Darken2);
                        row.AutoItem().AlignRight().Text(text =>
                        {
                            text.Span("Page ").FontSize(8).FontColor(Colors.Grey.Darken1);
                            text.CurrentPageNumber().FontSize(8).FontColor(Colors.Grey.Darken1);
                            text.Span(" of ").FontSize(8).FontColor(Colors.Grey.Darken1);
                            text.TotalPages().FontSize(8).FontColor(Colors.Grey.Darken1);
                        });
                    });
                    if (!string.IsNullOrWhiteSpace(model.FooterText))
                    {
                        footer.Item().PaddingTop(2).Text(model.FooterText).FontSize(8).FontColor(Colors.Grey.Darken1);
                    }
                });
            }))
            .GeneratePdf();
    }

    // ── Receipt PDF ──────────────────────────────────────────────────────────

    public byte[] RenderReceiptPdf(ReceiptPdfModel model)
    {
        QuestPDF.Settings.License = LicenseType.Community;

        var primary = model.PrimaryColor;

        return Document.Create(container =>
            container.Page(page =>
            {
                page.Size(PageSizes.A5);
                page.Margin(32);
                page.DefaultTextStyle(x => x.FontSize(10).FontFamily("Helvetica"));

                // ── Header ────────────────────────────────────────────────
                page.Header().Column(header =>
                {
                    header.Item().Row(row =>
                    {
                        row.RelativeItem().Column(col =>
                        {
                            col.Item().Text(model.CompanyName).FontSize(16).SemiBold().FontColor(primary);
                        });
                        row.AutoItem().AlignRight().Column(col =>
                        {
                            col.Item().Text("PAYMENT RECEIPT").FontSize(14).SemiBold().FontColor(primary);
                        });
                    });
                    header.Item().PaddingTop(6).BorderBottom(2).BorderColor(primary);
                });

                // ── Content ───────────────────────────────────────────────
                page.Content().PaddingTop(16).Column(column =>
                {
                    column.Spacing(10);

                    // Receipt details block
                    column.Item().Border(1).BorderColor(Colors.Grey.Lighten2).Padding(12).Column(col =>
                    {
                        col.Spacing(6);

                        void DetailRow(string label, string value, bool bold = false)
                        {
                            col.Item().Row(r =>
                            {
                                r.ConstantItem(120).Text(label).FontSize(9).SemiBold()
                                    .FontColor(Colors.Grey.Darken1);
                                var valSpan = r.RelativeItem().Text(value).FontSize(9);
                                if (bold) valSpan.SemiBold();
                            });
                        }

                        DetailRow("Receipt No.", model.ReceiptNumber, bold: true);
                        DetailRow("Invoice Ref.", model.InvoiceNumber);
                        DetailRow("Client", model.ClientName);
                        DetailRow("Payment Date", model.PaymentDate.ToString("dd MMM yyyy"));
                        DetailRow("Method", model.Method);
                        if (!string.IsNullOrWhiteSpace(model.Reference))
                            DetailRow("Reference", model.Reference);
                    });

                    // Large centred amount
                    column.Item().PaddingTop(8).AlignCenter().Column(amtCol =>
                    {
                        amtCol.Item().AlignCenter().Text("Amount Received")
                            .FontSize(9).FontColor(Colors.Grey.Darken1);
                        amtCol.Item().AlignCenter()
                            .Text($"{model.Currency} {model.Amount:N2}")
                            .FontSize(28).SemiBold().FontColor(primary);
                    });

                    // Thank-you line
                    column.Item().PaddingTop(8).AlignCenter()
                        .Text("Thank you for your payment!")
                        .FontSize(11).Italic().FontColor(Colors.Grey.Darken1);
                });

                // ── Footer ────────────────────────────────────────────────
                page.Footer().BorderTop(1).BorderColor(Colors.Grey.Lighten2).PaddingTop(6)
                    .AlignCenter()
                    .Text($"{model.CompanyName}  ·  Powered by Ecosys")
                    .FontSize(8).FontColor(Colors.Grey.Darken1);
            }))
            .GeneratePdf();
    }

    // ── Client Statement PDF ─────────────────────────────────────────────────

    public byte[] RenderClientStatementPdf(ClientStatementPdfModel model)
    {
        QuestPDF.Settings.License = LicenseType.Community;

        var primary   = model.PrimaryColor;
        Color redRow  = "#FEF2F2";  // light red for overdue rows
        var altRow    = Colors.Grey.Lighten4;

        return Document.Create(container =>
            container.Page(page =>
            {
                page.Margin(32);
                page.DefaultTextStyle(x => x.FontSize(10).FontFamily("Helvetica"));

                // ── Header ────────────────────────────────────────────────
                page.Header().Column(header =>
                {
                    header.Item().Row(row =>
                    {
                        row.RelativeItem().Column(col =>
                        {
                            col.Item().Text(model.CompanyName).FontSize(18).SemiBold().FontColor(primary);
                            var contact = new[] { model.CompanyPhone, model.CompanyAddress }
                                .Where(x => !string.IsNullOrWhiteSpace(x));
                            var contactLine = string.Join("  ·  ", contact);
                            if (!string.IsNullOrWhiteSpace(contactLine))
                                col.Item().Text(contactLine).FontSize(8).FontColor(Colors.Grey.Darken1);
                        });
                        row.AutoItem().AlignRight().Column(col =>
                        {
                            col.Item().Text("STATEMENT OF ACCOUNT").FontSize(18).SemiBold().FontColor(primary);
                            col.Item().AlignRight().Text($"Date: {model.StatementDate:dd MMM yyyy}").FontSize(9).FontColor(Colors.Grey.Darken1);
                        });
                    });
                    header.Item().PaddingTop(8).BorderBottom(2).BorderColor(primary);
                });

                // ── Content ───────────────────────────────────────────────
                page.Content().PaddingTop(12).Column(column =>
                {
                    column.Spacing(14);

                    // Client info + period strip
                    column.Item().Row(row =>
                    {
                        // Bill To
                        row.RelativeItem().Border(1).BorderColor(Colors.Grey.Lighten2).Padding(10).Column(col =>
                        {
                            col.Spacing(3);
                            col.Item().Text("CLIENT").FontSize(8).SemiBold().FontColor(Colors.Grey.Darken1);
                            col.Item().Text(model.ClientName).SemiBold();
                            if (!string.IsNullOrWhiteSpace(model.ClientAddress))
                                col.Item().Text(model.ClientAddress).FontSize(9).FontColor(Colors.Grey.Darken1);
                            if (!string.IsNullOrWhiteSpace(model.ClientEmail))
                                col.Item().Text(model.ClientEmail).FontSize(9).FontColor(Colors.Grey.Darken1);
                        });

                        row.ConstantItem(16); // spacer

                        // Period + summary
                        row.RelativeItem().Border(1).BorderColor(Colors.Grey.Lighten2).Padding(10).Column(col =>
                        {
                            col.Spacing(4);
                            col.Item().Row(r =>
                            {
                                r.RelativeItem().Text("Statement Period").FontSize(8).SemiBold().FontColor(Colors.Grey.Darken1);
                                r.AutoItem().Text($"{model.PeriodFrom:dd MMM yyyy} – {model.PeriodTo:dd MMM yyyy}").FontSize(9);
                            });
                            col.Item().Row(r =>
                            {
                                r.RelativeItem().Text("Opening Balance").FontSize(8).SemiBold().FontColor(Colors.Grey.Darken1);
                                r.AutoItem().Text($"KES {model.OpeningBalance:N2}").FontSize(9);
                            });
                            col.Item().Row(r =>
                            {
                                r.RelativeItem().Text("Total Invoiced").FontSize(8).SemiBold().FontColor(Colors.Grey.Darken1);
                                r.AutoItem().Text($"KES {model.TotalInvoiced:N2}").FontSize(9);
                            });
                            col.Item().Row(r =>
                            {
                                r.RelativeItem().Text("Total Paid").FontSize(8).SemiBold().FontColor(Colors.Grey.Darken1);
                                r.AutoItem().Text($"KES {model.TotalPaid:N2}").FontSize(9).FontColor(Colors.Green.Darken2);
                            });
                        });
                    });

                    // Balance due summary box
                    var balanceDue = model.ClosingBalance;
                    var balanceColor = balanceDue > 0 ? Colors.Red.Darken2 : Colors.Green.Darken2;
                    column.Item().Background(balanceDue > 0 ? Colors.Red.Lighten4 : Colors.Green.Lighten4)
                        .Border(1).BorderColor(balanceDue > 0 ? Colors.Red.Lighten2 : Colors.Green.Lighten2)
                        .Padding(12).Row(r =>
                        {
                            r.RelativeItem().Text("BALANCE DUE").FontSize(11).SemiBold().FontColor(balanceColor);
                            r.AutoItem().Text($"KES {balanceDue:N2}").FontSize(14).Bold().FontColor(balanceColor);
                        });

                    // Invoices table
                    if (model.Invoices.Count > 0)
                    {
                        column.Item().Column(tbl =>
                        {
                            tbl.Item().Text("Invoices").FontSize(11).SemiBold();
                            tbl.Item().PaddingTop(4).Table(table =>
                            {
                                table.ColumnsDefinition(cols =>
                                {
                                    cols.RelativeColumn(1.8f); // Invoice #
                                    cols.RelativeColumn(1.2f); // Date
                                    cols.RelativeColumn(1.2f); // Due Date
                                    cols.RelativeColumn(1.3f); // Amount
                                    cols.RelativeColumn(1.3f); // Paid
                                    cols.RelativeColumn(1.3f); // Balance
                                    cols.RelativeColumn(1.2f); // Status
                                });

                                IContainer HdrCell(IContainer c) =>
                                    c.Background(primary).Padding(6).AlignMiddle();

                                table.Header(h =>
                                {
                                    h.Cell().Element(HdrCell).Text("Invoice #").FontSize(8).SemiBold().FontColor(Colors.White);
                                    h.Cell().Element(HdrCell).Text("Date").FontSize(8).SemiBold().FontColor(Colors.White);
                                    h.Cell().Element(HdrCell).Text("Due Date").FontSize(8).SemiBold().FontColor(Colors.White);
                                    h.Cell().Element(HdrCell).AlignRight().Text("Amount").FontSize(8).SemiBold().FontColor(Colors.White);
                                    h.Cell().Element(HdrCell).AlignRight().Text("Paid").FontSize(8).SemiBold().FontColor(Colors.White);
                                    h.Cell().Element(HdrCell).AlignRight().Text("Balance").FontSize(8).SemiBold().FontColor(Colors.White);
                                    h.Cell().Element(HdrCell).Text("Status").FontSize(8).SemiBold().FontColor(Colors.White);
                                });

                                for (var i = 0; i < model.Invoices.Count; i++)
                                {
                                    var inv = model.Invoices[i];
                                    var bg = inv.IsOverdue ? redRow : (i % 2 == 0 ? Colors.White : altRow);

                                    IContainer DataCell(IContainer c) =>
                                        c.Background(bg).BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Padding(5).AlignMiddle();

                                    var statusColor = inv.Status switch
                                    {
                                        "Overdue" => Colors.Red.Darken2,
                                        "PartiallyPaid" => Colors.Orange.Darken2,
                                        _ => Colors.Grey.Darken2
                                    };

                                    table.Cell().Element(DataCell).Text(inv.InvoiceNumber).FontSize(8).SemiBold();
                                    table.Cell().Element(DataCell).Text(inv.InvoiceDate.ToString("dd MMM yy")).FontSize(8);
                                    table.Cell().Element(DataCell).Text(inv.DueDate.ToString("dd MMM yy")).FontSize(8).FontColor(inv.IsOverdue ? Colors.Red.Darken2 : Colors.Black);
                                    table.Cell().Element(DataCell).AlignRight().Text($"{inv.Amount:N2}").FontSize(8);
                                    table.Cell().Element(DataCell).AlignRight().Text($"{inv.Paid:N2}").FontSize(8).FontColor(Colors.Green.Darken2);
                                    table.Cell().Element(DataCell).AlignRight().Text($"{inv.Balance:N2}").FontSize(8).SemiBold().FontColor(inv.Balance > 0 ? Colors.Red.Darken2 : Colors.Green.Darken2);
                                    table.Cell().Element(DataCell).Text(inv.Status).FontSize(8).FontColor(statusColor).SemiBold();
                                }
                            });
                        });
                    }

                    // Payments table
                    if (model.Payments.Count > 0)
                    {
                        column.Item().Column(tbl =>
                        {
                            tbl.Item().Text("Payments").FontSize(11).SemiBold();
                            tbl.Item().PaddingTop(4).Table(table =>
                            {
                                table.ColumnsDefinition(cols =>
                                {
                                    cols.RelativeColumn(1.5f); // Date
                                    cols.RelativeColumn(2f);   // Ref
                                    cols.RelativeColumn(1.5f); // Method
                                    cols.RelativeColumn(1.5f); // Amount
                                });

                                IContainer HdrCell(IContainer c) =>
                                    c.Background(primary).Padding(6).AlignMiddle();

                                table.Header(h =>
                                {
                                    h.Cell().Element(HdrCell).Text("Date").FontSize(8).SemiBold().FontColor(Colors.White);
                                    h.Cell().Element(HdrCell).Text("Reference").FontSize(8).SemiBold().FontColor(Colors.White);
                                    h.Cell().Element(HdrCell).Text("Method").FontSize(8).SemiBold().FontColor(Colors.White);
                                    h.Cell().Element(HdrCell).AlignRight().Text("Amount").FontSize(8).SemiBold().FontColor(Colors.White);
                                });

                                for (var i = 0; i < model.Payments.Count; i++)
                                {
                                    var pmt = model.Payments[i];
                                    var bg = i % 2 == 0 ? Colors.White : altRow;

                                    IContainer DataCell(IContainer c) =>
                                        c.Background(bg).BorderBottom(1).BorderColor(Colors.Grey.Lighten3).Padding(5).AlignMiddle();

                                    table.Cell().Element(DataCell).Text(pmt.PaymentDate.ToString("dd MMM yy")).FontSize(8);
                                    table.Cell().Element(DataCell).Text(pmt.PaymentRef).FontSize(8).SemiBold();
                                    table.Cell().Element(DataCell).Text(pmt.Method).FontSize(8);
                                    table.Cell().Element(DataCell).AlignRight().Text($"KES {pmt.Amount:N2}").FontSize(8).FontColor(Colors.Green.Darken2);
                                }
                            });
                        });
                    }
                });

                // ── Footer ────────────────────────────────────────────────
                page.Footer().BorderTop(1).BorderColor(Colors.Grey.Lighten2).PaddingTop(6).Column(footer =>
                {
                    footer.Item().Text("This is a statement of your account. Please contact us if you have any queries.")
                        .FontSize(8).Italic().FontColor(Colors.Grey.Darken1).AlignCenter();
                    footer.Item().PaddingTop(4).Row(r =>
                    {
                        r.RelativeItem().Text(model.CompanyName).FontSize(8).FontColor(Colors.Grey.Darken2);
                        r.AutoItem().AlignRight().Text(text =>
                        {
                            text.Span("Page ").FontSize(8).FontColor(Colors.Grey.Darken1);
                            text.CurrentPageNumber().FontSize(8).FontColor(Colors.Grey.Darken1);
                            text.Span(" of ").FontSize(8).FontColor(Colors.Grey.Darken1);
                            text.TotalPages().FontSize(8).FontColor(Colors.Grey.Darken1);
                        });
                    });
                });
            }))
            .GeneratePdf();
    }
